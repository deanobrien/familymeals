// The parent PIN that keeps a child inside kids' mode (P3-A, D424). Pure and device-local: the PIN never leaves the phone or
// browser, only a salted, iterated SHA-256 of it is stored, and wrong guesses lock the gate for longer and longer. The PIN is a
// speed bump for a child, not a security boundary against someone with the unlocked device (the parent's session is on it anyway).
import { sha256Hex } from './sha256';

export const PIN_RE = /^\d{4,6}$/;
export const PIN_ITERATIONS = 3000;
/** Free wrong guesses before the first lock-out. */
export const FREE_ATTEMPTS = 3;
export const BASE_LOCK_MS = 30_000;
export const MAX_LOCK_MS = 15 * 60_000;

export interface PinRecord {
  /** Random hex, generated by the caller (crypto on the device) so this module stays pure. */
  salt: string;
  hash: string;
  iterations: number;
}

export interface GateState {
  /** Consecutive wrong guesses since the last success. */
  failures: number;
  /** Epoch ms until which every attempt is refused (0 = not locked). */
  lockedUntil: number;
}

export const OPEN_GATE: GateState = { failures: 0, lockedUntil: 0 };

export const isValidPin = (pin: unknown): pin is string => typeof pin === 'string' && PIN_RE.test(pin);

export function hashPin(pin: string, salt: string, iterations = PIN_ITERATIONS): string {
  let h = sha256Hex(`${salt}:${pin}`);
  for (let i = 1; i < iterations; i++) h = sha256Hex(`${salt}:${h}`);
  return h;
}

/** A PIN record to store, or null when the PIN is not 4-6 digits or the salt is not at least 16 hex characters. */
export function createPinRecord(pin: string, salt: string): PinRecord | null {
  if (!isValidPin(pin) || !/^[0-9a-f]{16,}$/i.test(salt)) return null;
  return { salt, hash: hashPin(pin, salt), iterations: PIN_ITERATIONS };
}

/** Defensive read of a stored record (anything malformed is "no PIN set"). */
export function parsePinRecord(v: unknown): PinRecord | null {
  if (!v || typeof v !== 'object') return null;
  const r = v as Record<string, unknown>;
  if (typeof r.salt !== 'string' || typeof r.hash !== 'string' || !/^[0-9a-f]{64}$/.test(r.hash) || typeof r.iterations !== 'number') return null;
  if (!Number.isInteger(r.iterations) || r.iterations < 1 || r.iterations > 100_000) return null;
  return { salt: r.salt, hash: r.hash, iterations: r.iterations };
}

export function parseGateState(v: unknown): GateState {
  if (!v || typeof v !== 'object') return OPEN_GATE;
  const r = v as Record<string, unknown>;
  const failures = typeof r.failures === 'number' && Number.isFinite(r.failures) ? Math.max(0, Math.floor(r.failures)) : 0;
  const lockedUntil = typeof r.lockedUntil === 'number' && Number.isFinite(r.lockedUntil) ? Math.max(0, r.lockedUntil) : 0;
  return { failures, lockedUntil };
}

/** How long the lock-out lasts after `failures` consecutive wrong guesses (0 while there are free attempts left). */
export function lockMsFor(failures: number): number {
  if (failures < FREE_ATTEMPTS) return 0;
  const doublings = failures - FREE_ATTEMPTS;
  return Math.min(MAX_LOCK_MS, BASE_LOCK_MS * 2 ** Math.min(doublings, 20));
}

const sameHash = (a: string, b: string): boolean => {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
};

export type PinAttempt =
  | { ok: true; state: GateState }
  | { ok: false; reason: 'locked'; state: GateState; retryAfterMs: number }
  | { ok: false; reason: 'wrong'; state: GateState; retryAfterMs: number; attemptsLeft: number }
  | { ok: false; reason: 'invalid'; state: GateState; retryAfterMs: 0 };

/**
 * Check one guess. While locked the guess is refused WITHOUT being checked (so a child cannot learn anything during the
 * lock-out) and does not extend it. A guess that is not 4-6 digits is "invalid" and costs nothing.
 */
export function attemptPin(record: PinRecord, guess: string, state: GateState, now: number): PinAttempt {
  if (state.lockedUntil > now) return { ok: false, reason: 'locked', state, retryAfterMs: state.lockedUntil - now };
  if (!isValidPin(guess)) return { ok: false, reason: 'invalid', state, retryAfterMs: 0 };
  if (sameHash(hashPin(guess, record.salt, record.iterations), record.hash)) return { ok: true, state: OPEN_GATE };
  const failures = state.failures + 1;
  const lock = lockMsFor(failures);
  const next: GateState = { failures, lockedUntil: lock > 0 ? now + lock : 0 };
  return { ok: false, reason: 'wrong', state: next, retryAfterMs: lock, attemptsLeft: Math.max(0, FREE_ATTEMPTS - failures) };
}

/** "30 seconds" / "2 minutes", for the lock message. */
export function lockLabel(ms: number): string {
  const s = Math.ceil(ms / 1000);
  if (s < 90) return `${s} second${s === 1 ? '' : 's'}`;
  const m = Math.ceil(s / 60);
  return `${m} minute${m === 1 ? '' : 's'}`;
}
