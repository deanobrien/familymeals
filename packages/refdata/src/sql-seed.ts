// SQL for the `public.ingredients` / `public.ingredient_aliases` reference rows (DECISIONS D145).
// The ids are the same stable UUIDv5 ids the app's catalogue uses, so a recipe line / pantry item that the engine
// matched keeps its `ingredient_id` when saved to Postgres (the FK columns are NULL for ids not in this table).
// Idempotent (ON CONFLICT DO NOTHING); `supabase/seed.sql` is generated from this by `pnpm --filter @fr/refdata build:sql-seed`.

export interface SeedIngredient {
  id: string;
  slug: string;
  name: string;
  category: string;
  form?: string;
  aliases: readonly string[];
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function ingredientsSeedSql(ingredients: readonly SeedIngredient[]): string {
  const sorted = [...ingredients].sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0)); // code-unit order: stable on every machine
  const rows = sorted.map((i) => `  (${q(i.id)}, ${q(i.name)}, ${q(i.slug)}, ${q(i.category)}, ${i.form ? `${q(i.form)}::public.ingredient_form` : 'null'})`);
  const aliases = sorted.flatMap((i) => [...i.aliases].sort().map((a) => `  (${q(i.id)}, ${q(a)})`));
  return [
    '-- GENERATED by `pnpm --filter @fr/refdata build:sql-seed` from packages/refdata (D145). Do not edit by hand.',
    '-- Reference ingredients + aliases with the catalogue ids, so saved recipe lines and pantry items keep their match.',
    '-- `supabase start` / `supabase db reset` apply it locally; a hosted project loads the same file once (service role).',
    'insert into public.ingredients (id, name, slug, category, form) values',
    rows.join(',\n'),
    'on conflict do nothing;',
    '',
    'insert into public.ingredient_aliases (ingredient_id, alias) values',
    aliases.join(',\n'),
    'on conflict do nothing;',
    '',
  ].join('\n');
}
